// Usage: node tools/map-editions.mjs --game <name>
// Finds the main edition's code addresses (games/<name>/patches.json, entries.json and
// coverage.txt) in each other edition set up in local.json, and saves them in
// games/<name>/editions.json: addresses only, no bytes of any game. Needs the main edition's
// ROM, which the addresses are written for. Run it after adding or changing an address.
//
// Every patch and entry address must be found (or be listed as absent for that edition in
// game.json); codegen then checks each patched instruction is the one it expects.
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { GAME, GAME_DIR, gameFile } from './lib/game.mjs';
import { loadRoms } from './lib/rom.mjs';
import { loadCoverageList } from './lib/inputs.mjs';
import { addressesIn, hex6, mapAddresses, mapCoverage, remapConfig, sameInstruction } from './lib/editions.mjs';

const roms = loadRoms();
const main = roms.find((r) => r.edition.main);
if (!main) { console.error(`The ${GAME} main edition's ROM is needed: the addresses are found from it.`); process.exit(1); }
const patches = gameFile('patches.json', {}), entries = gameFile('entries.json', []);
const wanted = [...addressesIn({ patches, entries })].sort((a, b) => a - b);
const coverage = loadCoverageList();

const file = join(GAME_DIR, 'editions.json');
const out = existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : {};
out.comment = 'Generated by tools/map-editions.mjs: the main edition\'s patch, entry and coverage addresses in each other edition. Do not edit.';
let failed = false;
for (const { edition, rom } of roms) {
  if (edition.main || edition.sameCodeAs) continue;
  const absent = new Set((edition.absent || []).map((s) => parseInt(s, 16)));
  const map = mapAddresses(main.rom, rom, wanted.filter((a) => !absent.has(a)));
  for (const [a, b] of Object.entries(edition.placed || {})) {
    if (!sameInstruction(main.rom, parseInt(a, 16), rom, parseInt(b, 16))) { console.error(`${edition.name}: placed ${a} at ${b}, where the instruction differs`); failed = true; }
    else map.set(parseInt(a, 16), parseInt(b, 16));
  }
  const missing = wanted.filter((a) => !absent.has(a) && !map.has(a));
  if (missing.length) {
    console.error(`${edition.name}: not found: ${missing.map(hex6).join(', ')} (list any it does not have as "absent" in game.json)`);
    failed = true;
    continue;
  }
  const cov = [...new Set(mapCoverage(main.rom, rom, coverage))].sort((a, b) => a - b), ranges = [];
  for (let k = 0; k < cov.length; ) {
    let j = k;
    while (j + 1 < cov.length && cov[j + 1] === cov[j] + 2) j++;
    ranges.push(j > k ? `${hex6(cov[k])}-${hex6(cov[j])}` : hex6(cov[k]));
    k = j + 1;
  }
  out[edition.id] = {
    patches: remapConfig(patches, map, absent),
    entries: remapConfig(entries, map, absent),
    coverage: ranges,
  };
  console.log(`${edition.name}: ${map.size} addresses found (${absent.size} absent), ${cov.length} of ${coverage.length} covered addresses`);
}
writeFileSync(file, JSON.stringify(out, null, 1) + '\n');
if (failed) process.exit(1);
