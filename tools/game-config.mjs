// Writes what the C build needs to know about the chosen game, from games/<name>/game.json:
//   build/<name>/config/game_config.h  the defines runtime/src/game.h includes
//   build/<name>/config/game.cmake     the executable's name
// CMake runs this when it configures, and again whenever game.json changes.
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { GAME, GAME_INFO, BUILD_DIR } from './lib/game.mjs';

const dir = join(BUILD_DIR, 'config');
mkdirSync(dir, { recursive: true });
const writeIfChanged = (path, text) => {
  if (existsSync(path) && readFileSync(path, 'utf8') === text) return;
  writeFileSync(path, text);
};
const f = GAME_INFO.features || {};
const str = (s) => JSON.stringify(String(s));
writeIfChanged(join(dir, 'game_config.h'), [
  `/* Generated by tools/game-config.mjs from games/${GAME}/game.json. Do not edit. */`,
  `#define GAME_TITLE      ${str(GAME_INFO.title)}`,
  `#define GAME_ROM_NAME   ${str(GAME_INFO.rom.name)}`,
  `#define GAME_ROM_SHA1   ${str(GAME_INFO.rom.sha1)}`,
  `#define GAME_ROM_SIZE   0x${GAME_INFO.rom.size.toString(16).toUpperCase()}`,
  `#define GAME_KNOWS_RAM  ${f.ram ? 1 : 0}`,
  `#define GAME_WIDESCREEN ${f.widescreen ? 1 : 0}`,
  `#define GAME_LAUNCHER   ${f.launcher ? 1 : 0}`,
  `#define GAME_SOR        ${GAME_INFO.series || 0}   /* which Streets of Rage (1-3), 0 for another game */`,
  `#define GAME_WIDE_VIEW  ${f.wideView ? 1 : 0}   /* a wider picture from the game's own patches (sorWide) */`,
  `#define GAME_SMPS       ${f.smps ? 1 : 0}   /* the sound driver is Sega's SMPS 68k (ost.c) */`,
  `#define GAME_FIGHTERS   ${f.fighters ? 1 : 0}   /* the fighters' colours (fighters.c) */`,
  `#define GAME_SRAM_ALWAYS ${GAME_INFO.sram?.always ? 1 : 0}   /* battery save mapped at $200001 from the start */`,
  '',
].join('\n'));
writeIfChanged(join(dir, 'game.cmake'), `set(GAME_EXE ${GAME_INFO.exe})\n`);
console.log(`${GAME}: ${GAME_INFO.title} (${GAME_INFO.exe}.exe)`);
