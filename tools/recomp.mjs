// Generates C for every traced block of each edition of the game set up in local.json:
//   generated/<game>/<id>/recomp_00.c .. recomp_15.c  - block functions plus a per-file table
//   generated/<game>/<id>/edition.c                   - the edition's tables (GameEdition)
//   generated/<game>/editions.c                       - every edition in game.json, NULL for
//                                                       the ones not set up
// The file counts are fixed so the build system knows the outputs in advance.
import { mkdirSync, writeFileSync, readFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';
import { loadRoms } from './lib/rom.mjs';
import { GEN_DIR, EDITIONS } from './lib/game.mjs';
import { trace } from './lib/trace.mjs';
import { loadExtraEntries } from './lib/inputs.mjs';
import { genBlock, usePatches } from './lib/codegen.mjs';
import { configFor } from './lib/editions.mjs';

export const CHUNKS = 16;

// Only rewrite files whose content changed, so the C build stays incremental.
const writeIfChanged = (path, text) => {
  if (existsSync(path) && readFileSync(path, 'utf8') === text) return;
  writeFileSync(path, text);
};

const header = '/* Generated by tools/recomp.mjs from the user\'s ROM. Do not edit or distribute. */\n#include "recomp_rt.h"\n\n';
const chunk = (c) => String(c).padStart(2, '0');
const cstr = (s) => JSON.stringify(s).replace(/[\u0080-￿]/g, (c) =>
  [...Buffer.from(c, 'utf8')].map((b) => `\\x${b.toString(16)}`).join('') + '""');
const REGION = { us: 'REGION_US', eu: 'REGION_EU', jp: 'REGION_JP' };

const built = new Set();
for (const { edition, rom } of loadRoms()) {
  const config = configFor(edition);
  usePatches(config.patches);
  const t = trace(rom, loadExtraEntries(edition, edition.main ? null : config));
  const parts = t.blocks.flatMap((b) => genBlock(rom, b));
  const id = edition.id, outDir = join(GEN_DIR, id);
  mkdirSync(outDir, { recursive: true });

  const per = Math.ceil(parts.length / CHUNKS);
  for (let c = 0; c < CHUNKS; c++) {
    const mine = parts.slice(c * per, (c + 1) * per);
    const body = mine.map((p) => p.code).join('\n');
    const table = mine.flatMap((p) => p.entries.map((pc) => `    { 0x${pc.toString(16).toUpperCase()}, ${p.name} },`)).join('\n');
    writeIfChanged(join(outDir, `recomp_${chunk(c)}.c`), header + body +
      `\nconst RecompEntry recomp_table_${id}_${chunk(c)}[] = {\n${table}\n    { 0, 0 }\n};\n`);
  }
  const tables = [...Array(CHUNKS).keys()].map((c) => `recomp_table_${id}_${chunk(c)}`);
  writeIfChanged(join(outDir, 'edition.c'), header + '#include "game.h"\n\n' +
    tables.map((n) => `extern const RecompEntry ${n}[];`).join('\n') +
    `\n\nstatic const RecompEntry *const tables[] = {\n${tables.map((n) => `    ${n},`).join('\n')}\n    0\n};\n\n` +
    `const GameEdition game_edition_${id} = {\n` +
    `    .id = "${id}", .name = ${cstr(edition.name)}, .edition = ${cstr(edition.edition)},\n` +
    (edition.title ? `    .title = ${cstr(edition.title)},\n` : '') +
    `    .sha1 = "${edition.sha1}", .region = ${REGION[edition.region]}, .is_main = ${edition.main ? 1 : 0}, .tables = tables,\n` +
    `};\n`);
  built.add(id);
  console.log(`${edition.name}: recompiled ${parts.length} block functions from ${t.blocks.length} blocks into ${CHUNKS} files`);
}

// Every edition has its files, so the build's file list does not depend on which were set
// up; one not set up gets empty ones (and is NULL in the list).
for (const e of EDITIONS) {
  if (built.has(e.id)) continue;
  const outDir = join(GEN_DIR, e.id);
  mkdirSync(outDir, { recursive: true });
  for (let c = 0; c < CHUNKS; c++) writeIfChanged(join(outDir, `recomp_${chunk(c)}.c`), header + '/* This edition is not set up. */\n');
  writeIfChanged(join(outDir, 'edition.c'), header + '/* This edition is not set up. */\n');
}
writeIfChanged(join(GEN_DIR, 'editions.c'), header + '#include "game.h"\n\n' +
  EDITIONS.filter((e) => built.has(e.id)).map((e) => `extern const GameEdition game_edition_${e.id};`).join('\n') +
  `\n\nconst GameEdition *const game_editions[GAME_EDITION_COUNT] = {\n` +
  EDITIONS.map((e) => `    ${built.has(e.id) ? `&game_edition_${e.id}` : 'NULL'},`).join('\n') + '\n};\n' +
  '\n/* Every edition\'s cartridge, built or not: one not built is recognised and named. */\n' +
  `const char *const game_edition_sha1s[GAME_EDITION_COUNT] = {\n` + EDITIONS.map((e) => `    ${JSON.stringify(e.sha1)},`).join('\n') + '\n};\n' +
  `const char *const game_edition_names[GAME_EDITION_COUNT] = {\n` + EDITIONS.map((e) => `    ${JSON.stringify(e.name)},`).join('\n') + '\n};\n');
